import 'dart:convert';
import 'dart:io';

import 'package:archive/archive.dart';
import 'package:dartc/sdk.dart';

import 'src/sdk_sources.dart';

Future<void> main() async {
  final sdk = await SdkSources(Directory('build/sources/sdk')).prepare();
  final archive = Archive();
  final files = sdk.listSync(recursive: true).whereType<File>().toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  for (final file in files) {
    final name = file.uri.pathSegments
        .skip(sdk.uri.pathSegments.length - 1)
        .join('/');
    archive.add(
      ArchiveFile(name, file.lengthSync(), file.readAsBytesSync())
        ..lastModTime = 0,
    );
  }
  final encoded = base64.encode(gzip.encode(TarEncoder().encode(archive)));
  final output = StringBuffer('// Generated by tool/embed_sdk.dart. Do not edit.\n')
    ..writeln(
      '// Original sources and license: https://github.com/dart-lang/sdk/tree/${DartSdk.sourceRevision}/sdk/lib',
    )
    ..write('const sdkArchive =\n');
  for (var start = 0; start < encoded.length; start += 8192) {
    final end = start + 8192 < encoded.length ? start + 8192 : encoded.length;
    output.writeln(
      "    '${encoded.substring(start, end)}'${end == encoded.length ? ';' : ''}",
    );
  }
  await File('lib/src/sdk/sources.g.dart').writeAsString(output.toString());

  stdout.writeln('Embedded ${files.length} official SDK files.');
}
