/// [point] in the other case that [ranges] give.
int _changeCase(int point, List<int> ranges) {
  var low = 0, high = ranges.length >> 2;
  while (low < high) {
    final middle = (low + high) >> 1;
    if (ranges[middle * 4] <= point) {
      low = middle + 1;
    } else {
      high = middle;
    }
  }
  if (low == 0) return point;
  final at = (low - 1) * 4, step = ranges[at + 2];
  final distance = point - ranges[at];
  if (distance == 0) return point + ranges[at + 3];
  if (step == 0 || distance % step != 0) return point;
  return distance ~/ step < ranges[at + 1] ? point + ranges[at + 3] : point;
}

@patch
class _StringBase {
  String _withCase(List<int> ranges) {
    // Finds out whether there is something to change first.
    final length = this.length;
    var at = 0;
    while (at < length) {
      final unit = _unitAt(at);
      if (unit >= 0xd800 && unit < 0xdc00 || _changeCase(unit, ranges) != unit) {
        break;
      }
      at++;
    }
    if (at == length) return this;
    final points = <int>[];
    for (final point in Runes(this)) {
      points.add(_changeCase(point, ranges));
    }
    return String.fromCharCodes(points);
  }

  @patch
  String toUpperCase() => _withCase(_upperCases);

  @patch
  String toLowerCase() => _withCase(_lowerCases);
}
